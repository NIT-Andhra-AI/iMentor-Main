function downloadFile(content, fileName, mimeType) {
    const blob = new Blob([content], { type: mimeType });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = fileName;
    document.body.appendChild(a);
    a.click();
    setTimeout(() => {
        document.body.removeChild(a);
        URL.revokeObjectURL(url);
    }, 200);
}

function exportBibTeX(title, sources = []) {
    if (!sources || sources.length === 0) {
        toast.error('No source metadata available for BibTeX export');
        return;
    }
    const bibEntries = sources.map((s, idx) => {
        const firstAuthor = (s.authors?.[0]?.split(' ').pop() || 'author').replace(/[^a-zA-Z]/g, '');
        const year = s.year || s.publishedYear || new Date().getFullYear();
        const key = `${firstAuthor.toLowerCase()}${year}_source${idx + 1}`;
        const cleanTitle = (s.title || 'Untitled').replace(/[{}]/g, '');
        const authors = Array.isArray(s.authors) ? s.authors.join(' and ') : (s.authors || 'Unknown');
        const journal = s.journal || s.venue || s.publisher || (s.sourceProvider === 'arxiv' ? 'arXiv preprint' : 'Academic Reference');
        const doi = s.doi ? `,\n  doi = {${s.doi}}` : '';
        const url = s.url ? `,\n  url = {${s.url}}` : '';
        return `@article{${key},\n  title = {${cleanTitle}},\n  author = {${authors}},\n  journal = {${journal}},\n  year = {${year}}${doi}${url}\n}`;
    }).join('\n\n');
    downloadFile(bibEntries, `${(title || 'research').replace(/[^a-zA-Z0-9]/g, '_')}_citations.bib`, 'text/plain');
    toast.success('BibTeX citations exported!');
}

function exportMarkdown(title, report, sources = []) {
    let md = `# ${title || report.query || 'Analytical Synthesis Report'}\n\n`;
    md += `*Generated by iMentor Deep Research Hybrid Knowledge Engine*\n`;
    md += `*Date: ${new Date().toLocaleDateString()} | System Confidence: ${report.overallConfidenceScore || 90}%*\n\n`;

    if (report.executiveSummary?.analyticalOverview) {
        md += `## I. Executive Summary\n\n${report.executiveSummary.analyticalOverview}\n\n`;
        if (report.executiveSummary.primaryDriver) md += `**Primary Causal Driver:** ${report.executiveSummary.primaryDriver}\n\n`;
        if (report.executiveSummary.primaryContradiction) md += `**Crucial Contradictory Metric:** ${report.executiveSummary.primaryContradiction}\n\n`;
        if (report.executiveSummary.strongestInsight) md += `**Core Insight:** ${report.executiveSummary.strongestInsight}\n\n`;
    }

    (report.sections || []).forEach((sec, idx) => {
        md += `## 0${idx + 2}. ${sec.title}\n\n${sec.content}\n\n`;
        if (sec.causalMechanism) md += `> **Causal Mechanism:** ${sec.causalMechanism}\n\n`;
        if (sec.quantitativeSignals?.length) {
            md += `### Quantitative Signals\n`;
            sec.quantitativeSignals.forEach(sig => { md += `- ${sig}\n`; });
            md += `\n`;
        }
    });

    if (sources && sources.length > 0) {
        md += `## Verified References & Academic Sources\n\n`;
        sources.forEach((s, idx) => {
            const authors = Array.isArray(s.authors) ? s.authors.join(', ') : (s.authors || 'Unknown');
            const link = s.doi ? `https://doi.org/${s.doi}` : s.url || '';
            md += `[${idx + 1}] **${s.title}** - ${authors} (${s.year || 'n.d.'}). *${s.journal || s.publisher || s.sourceProvider || ''}* ${link ? `[Link](${link})` : ''}\n\n`;
        });
    }

    downloadFile(md, `${(title || 'research').replace(/[^a-zA-Z0-9]/g, '_')}_report.md`, 'text/markdown');
    toast.success('Markdown report exported!');
}

