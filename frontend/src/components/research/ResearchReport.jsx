function downloadFile(content, fileName, mimeType) {
    const blob = content instanceof Blob ? content : new Blob([content], { type: mimeType });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = fileName;
    document.body.appendChild(a);
    a.click();
    setTimeout(() => {
        document.body.removeChild(a);
        URL.revokeObjectURL(url);
    }, 250);
}

function exportBibTeX(title, sources = []) {
    if (!sources || sources.length === 0) {
        toast.error('No source metadata available for BibTeX export');
        return;
    }
    const bibEntries = sources.map((s, idx) => {
        const citNum = s.citationIndex || (idx + 1);
        const firstAuthor = (s.authors?.[0]?.split(' ').pop() || 'author').replace(/[^a-zA-Z]/g, '');
        const year = s.year || s.publishedYear || new Date().getFullYear();
        const key = `ref${citNum}_${firstAuthor.toLowerCase()}${year}`;
        const cleanTitle = (s.title || 'Untitled').replace(/[{}]/g, '');
        const authors = Array.isArray(s.authors) ? s.authors.join(' and ') : (s.authors || 'Unknown');
        const journal = s.journal || s.venue || s.publisher || (s.sourceProvider === 'arxiv' ? 'arXiv preprint' : 'Academic Reference');
        const doi = s.doi ? `,\n  doi = {${s.doi}}` : '';
        const url = (s.openAccessUrl || s.url) ? `,\n  url = {${s.openAccessUrl || s.url}}` : '';
        return `@article{${key},\n  title = {{${cleanTitle}}},\n  author = {${authors}},\n  journal = {${journal}},\n  year = {${year}}${doi}${url}\n}`;
    }).join('\n\n');
    downloadFile(bibEntries, `${(title || 'research').replace(/[^a-zA-Z0-9]/g, '_').slice(0, 40)}_references.bib`, 'text/plain');
    toast.success('BibTeX citations exported!');
}

function exportComparisonCSVClient(title, matrix = [], customCols = []) {
    if (!matrix || matrix.length === 0) {
        toast.error('No comparison matrix rows available');
        return;
    }
    const esc = (v) => `"${String(v ?? '').replace(/\r?\n/g, ' ').replace(/"/g, '""').trim()}"`;
    const headers = ['Ref', 'Paper_Title', 'Authors_Year_Venue', 'Core_Problem', 'Methodology', 'Datasets_And_Setup', 'Key_Quantitative_Metrics', 'Limitations_And_Gaps', ...customCols.map(c => c.label || c.key), 'Full_Text_Parsed'];
    const rows = [headers.join(',')];
    for (const r of matrix) {
        rows.push([
            esc(`[${r.citationIndex}]`),
            esc(r.paperTitle),
            esc(r.authorsYearVenue),
            esc(r.coreProblem),
            esc(r.methodology),
            esc(r.datasetsAndSetup),
            esc(r.keyMetrics),
            esc(r.limitationsAndGaps),
            ...customCols.map(c => esc(r.customFields?.[c.key] || 'N/A')),
            esc(r.hasFullText ? 'Yes' : 'No')
        ].join(','));
    }
    downloadFile(rows.join('\n'), `${(title || 'research').replace(/[^a-zA-Z0-9]/g, '_').slice(0, 40)}_Comparison_Matrix.csv`, 'text/csv;charset=utf-8');
    toast.success('Comparison Matrix (.csv) downloaded!');
}

function exportMarkdown(title, report, sources = []) {
    const matrix = Array.isArray(report.comparisonMatrix) ? report.comparisonMatrix : [];
    const gaps = Array.isArray(report.phdResearchDirections) ? report.phdResearchDirections : [];
    let md = `# ${report.title || title || report.query || 'PhD Literature Review Report'}\n\n`;
    md += `*Generated by iMentor PhD Literature Review & Institutional Full-Text Engine*  \n`;
    md += `*Date: ${new Date().toLocaleDateString()} | System Confidence: ${report.overallConfidenceScore || 90}% | Sources: ${sources.length}*\n\n`;

    if (report.executiveSummary?.analyticalOverview) {
        md += `## I. Executive Summary\n\n${report.executiveSummary.analyticalOverview}\n\n`;
        if (report.executiveSummary.primaryDriver) md += `**Primary Methodological / Physical Driver:** ${report.executiveSummary.primaryDriver}\n\n`;
        if (report.executiveSummary.primaryContradiction) md += `**Primary Empirical Contradiction:** ${report.executiveSummary.primaryContradiction}\n\n`;
        if (report.executiveSummary.strongestInsight) md += `**Decisive Finding:** ${report.executiveSummary.strongestInsight}\n\n`;
    }

    if (matrix.length > 0) {
        md += `## II. Literature Comparison Matrix\n\n`;
        md += `| Ref | Study & Venue | Core Problem | Methodology | Datasets & Setup | Key Metrics | Limitations |\n`;
        md += `| :--- | :--- | :--- | :--- | :--- | :--- | :--- |\n`;
        matrix.forEach(r => {
            const c = (v) => String(v || 'N/A').replace(/\|/g, '/').replace(/\r?\n/g, ' ');
            md += `| [${r.citationIndex}] | **${c(r.paperTitle)}** (${c(r.authorsYearVenue)}) | ${c(r.coreProblem)} | ${c(r.methodology)} | ${c(r.datasetsAndSetup)} | ${c(r.keyMetrics)} | ${c(r.limitationsAndGaps)} |\n`;
        });
        md += `\n`;
    }

    (report.sections || []).forEach((sec, idx) => {
        md += `## 0${idx + 3}. ${sec.title}\n\n${sec.content}\n\n`;
        if (sec.causalMechanism) md += `> **Governing Mechanism:** ${sec.causalMechanism}\n\n`;
    });

    if (gaps.length > 0) {
        md += `## Open PhD Research Gaps & Future Thesis Directions\n\n`;
        gaps.forEach((g, idx) => {
            md += `### Gap ${idx + 1}: ${g.gapTitle}\n`;
            md += `- **Contradiction / Lacuna:** ${g.contradictionOrLacuna}\n`;
            md += `- **Proposed PhD Contribution:** ${g.proposedPhdDirection}\n`;
            md += `- **Suggested Methodology:** ${g.suggestedMethodology}\n`;
            md += `- **Target Benchmarks:** ${g.targetDatasetsAndMetrics}\n\n`;
        });
    }

    if (sources && sources.length > 0) {
        md += `## Verified Scholarly References\n\n`;
        sources.forEach((s, idx) => {
            const citNum = s.citationIndex || (idx + 1);
            const authors = Array.isArray(s.authors) ? s.authors.join(', ') : (s.authors || 'Unknown');
            const link = s.doi ? `https://doi.org/${s.doi}` : (s.openAccessUrl || s.url || '');
            const ftBadge = s.hasFullText ? ' **[Full-Text PDF Parsed]**' : '';
            md += `[${citNum}] **${s.title}** - ${authors} (${s.year || 'n.d.'}). *${s.journal || s.publisher || s.sourceProvider || ''}*${ftBadge} ${link ? `[Link](${link})` : ''}\n\n`;
        });
    }

    downloadFile(md, `${(title || 'research').replace(/[^a-zA-Z0-9]/g, '_').slice(0, 40)}_report.md`, 'text/markdown');
    toast.success('Markdown report exported!');
}

